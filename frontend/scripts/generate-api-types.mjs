/**
 * Generate TypeScript types from every backend service's OpenAPI document.
 *
 *   npm run gen:api            # services must be running (./local/dev.sh up)
 *
 * The gateway's own routes are thin proxies, so the real request/response
 * schemas come from each service. One module per service lands in
 * types/api/<service>.ts; import `paths` / `components` from there instead of
 * hand-writing shapes that drift from the backend.
 */
import { mkdir, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const HOST = process.env.API_TYPES_HOST ?? "http://127.0.0.1";

// Ports as in the local-dev table in CLAUDE.md.
const SERVICES = [
  ["user", 8001],
  ["product", 8002],
  ["notification", 8003],
  ["order", 8005],
  ["payment", 8006],
  ["cart", 8007],
  ["shipping", 8008],
  ["wishlist", 8009],
  ["supplier", 8010],
];

const OUT_DIR = new URL("../types/api/", import.meta.url);
const HEADER =
  "/**\n * GENERATED by scripts/generate-api-types.mjs from the service's /openapi.json.\n" +
  " * Do not edit by hand - run `npm run gen:api`.\n */\n\n";

async function generate([name, port]) {
  const url = `${HOST}:${port}/openapi.json`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${name}: ${url} answered ${response.status}`);
  }
  const ast = await openapiTS(await response.json());
  await writeFile(new URL(`${name}.ts`, OUT_DIR), HEADER + astToString(ast));
  return name;
}

await mkdir(OUT_DIR, { recursive: true });
const results = await Promise.allSettled(SERVICES.map(generate));
let failed = 0;
for (const result of results) {
  if (result.status === "fulfilled") {
    console.log(`  ok  ${result.value}`);
  } else {
    failed += 1;
    console.error(`  !!  ${result.reason.message}`);
  }
}
if (failed) {
  console.error(`${failed} service(s) failed - is the stack up? (./local/dev.sh up)`);
  process.exit(1);
}
